// Helper to build day mapping for 1..31 (Only 'planned' [R] and 'none' [-] status)
export const createProgramDays = (
  activeDays: number[],
  doneDays: number[] = [],
  inProgressDays: number[] = [],
  rescheduledDays: number[] = []
): Record<number, ProgramDayStatus> => {
  const result: Record<number, ProgramDayStatus> = {};
  for (let d = 1; d <= 31; d++) {
    if (
      activeDays.includes(d) ||
      doneDays.includes(d) ||
      inProgressDays.includes(d) ||
      rescheduledDays.includes(d)
    ) {
      result[d] = 'planned';
    } else {
      result[d] = 'none';
    }
  }
  return result;
};

